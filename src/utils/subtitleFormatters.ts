import { SubtitleSegment } from '../types';

function formatSRTTime(seconds: number): string {
  const pad = (num: number, size = 2) => String(Math.floor(num)).padStart(size, '0');
  const hrs = pad(seconds / 3600);
  const mins = pad((seconds % 3600) / 60);
  const secs = pad(seconds % 60);
  const ms = String(Math.floor((seconds % 1) * 1000)).padStart(3, '0');
  return `${hrs}:${mins}:${secs},${ms}`;
}

function formatVTTTime(seconds: number): string {
  const pad = (num: number, size = 2) => String(Math.floor(num)).padStart(size, '0');
  const hrs = pad(seconds / 3600);
  const mins = pad((seconds % 3600) / 60);
  const secs = pad(seconds % 60);
  const ms = String(Math.floor((seconds % 1) * 1000)).padStart(3, '0');
  return `${hrs}:${mins}:${secs}.${ms}`;
}

export function generateSRT(segments: SubtitleSegment[]): string {
  return segments
    .map((seg, idx) => {
      const startTime = formatSRTTime(seg.start);
      const endTime = formatSRTTime(seg.end);
      return `${idx + 1}\n${startTime} --> ${endTime}\n${seg.translatedText}\n`;
    })
    .join('\n');
}

export function generateVTT(segments: SubtitleSegment[]): string {
  const header = 'WEBVTT - Generated by Video Translate AI\n\n';
  const body = segments
    .map((seg, idx) => {
      const startTime = formatVTTTime(seg.start);
      const endTime = formatVTTTime(seg.end);
      return `${idx + 1}\n${startTime} --> ${endTime}\n${seg.translatedText}\n`;
    })
    .join('\n');
  return header + body;
}

export function downloadTextFile(content: string, filename: string, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
